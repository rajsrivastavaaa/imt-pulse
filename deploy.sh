#!/usr/bin/env bash
# Deploy everything (backend stack + web app). Usage: ./deploy.sh
set -euo pipefail
cd "$(dirname "$0")"
STACK=imt-pulse
REGION=ap-southeast-2
export AWS_PAGER="" SAM_CLI_TELEMETRY=0
SAM=.venv/bin/sam

$SAM validate --lint --region "$REGION"
$SAM deploy --stack-name "$STACK" --region "$REGION" --capabilities CAPABILITY_IAM \
  --resolve-s3 --no-confirm-changeset --no-fail-on-empty-changeset

out() { aws cloudformation describe-stacks --stack-name "$STACK" --region "$REGION" \
  --query "Stacks[0].Outputs[?OutputKey=='$1'].OutputValue" --output text; }

cat > frontend/config.js <<CFG
// Generated by deploy.sh — do not edit by hand.
window.PULSE_CONFIG = {
  apiUrl: "$(out ApiUrl)",
  region: "$REGION",
  userPoolClientId: "$(out UserPoolClientId)"
};
CFG

BUCKET=$(out WebBucketName)
# HTML, service worker and config must never be stale; everything else can cache.
aws s3 sync frontend/ "s3://$BUCKET/" --delete --region "$REGION" \
  --exclude "*.html" --exclude "sw.js" --exclude "config.js" --exclude "*.webmanifest" \
  --cache-control "public,max-age=86400"
aws s3 sync frontend/ "s3://$BUCKET/" --region "$REGION" \
  --exclude "*" --include "*.html" --include "sw.js" --include "config.js" --include "*.webmanifest" \
  --cache-control "no-cache"
aws cloudfront create-invalidation --distribution-id "$(out DistributionId)" --paths "/*" >/dev/null
echo "Deployed. App: $(out AppUrl)"
