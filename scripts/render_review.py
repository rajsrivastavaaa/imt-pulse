"""Render samples/*.json into one readable HTML page (samples/review.html) for quality review."""
import glob
import html
import json
import sys

SRC = sys.argv[1] if len(sys.argv) > 1 else "samples"
TITLE = sys.argv[2] if len(sys.argv) > 2 else "Sonnet 4.6 writing, Haiku 4.5 tagging"

TRACK_NAMES = {"marketing": "Marketing", "finance": "Finance", "consulting": "Consulting / Strategy", "ops": "Ops / Analytics"}
e = html.escape


def quiz_html(quiz):
    out = []
    for n, q in enumerate(quiz, 1):
        opts = "".join(f'<li class="{"ok" if j == q["answer_index"] else ""}">{e(o)}</li>' for j, o in enumerate(q["options"]))
        out.append(f'<div class="q"><b>Q{n}. {e(q["question"])}</b><ol type="A">{opts}</ol>'
                   f'<p class="ex">{e(q["explanation"])}</p></div>')
    return "".join(out)


days = []
for path in sorted(glob.glob(f"{SRC}/2026-*.json"), reverse=True):
    d = json.load(open(path))
    parts = [f'<h2>{e(d["date"])} <small>{d["_run"]["items"]} feed items · {d["_run"]["calls"]} Bedrock calls · ~${d["_run"]["approx_usd"]}</small></h2>']
    c = d.get("company")
    if c:
        if c.get("error"):
            parts.append(f'<section class="card co"><h3>Company of the Day: {e(c["name"])}</h3><p class="err">FAILED: {e(c["error"])}</p></section>')
        else:
            news = "".join(f'<li>{e(n["point"])} <a href="{e(n["link"])}" target="_blank">{e(n["source"])}</a></li>' for n in c["recent_news"]) or "<li><i>No news in the feeds today</i></li>"
            parts.append(
                f'<section class="card co"><span class="badge">AI-written brief: double-check before your interview</span>'
                f'<h3>Company of the Day: {e(c["name"])} <small>process on {e(c["process_date"])}</small></h3>'
                f'<p>{e(c["what_it_does"])}</p><h4>Business lines</h4><ul>{"".join(f"<li>{e(b)}</li>" for b in c["business_lines"])}</ul>'
                f'<h4>Recent news</h4><ul>{news}</ul><h4>Talking points</h4><ol>{"".join(f"<li>{e(t)}</li>" for t in c["talking_points"])}</ol>'
                f'<details><summary>Company quiz ({len(c["quiz"])})</summary>{quiz_html(c["quiz"])}</details></section>')
    for t, sec in d["tracks"].items():
        if sec.get("error"):
            parts.append(f'<section class="card"><h3>{TRACK_NAMES[t]}</h3><p class="err">FAILED: {e(sec["error"])}</p></section>')
            continue
        stories = "".join(
            f'<li><a href="{e(s["link"])}" target="_blank">{e(s["headline"])}</a> <span class="src">{e(s["source"])}</span>'
            f'<p>{e(s["summary"])}</p><p class="why">Why it matters: {e(s["why_it_matters"])}</p></li>' for s in sec["stories"])
        warn = f'<p class="err">{e(sec["warning"])}</p>' if sec.get("warning") else ""
        parts.append(f'<section class="card"><h3>{TRACK_NAMES[t]} <small>{len(sec["stories"])} stories</small></h3>{warn}<ol class="stories">{stories}</ol>'
                     f'<details><summary>Quiz ({len(sec["quiz"])} questions, correct answer highlighted)</summary>{quiz_html(sec["quiz"])}</details></section>')
    days.append("".join(parts))

page = f"""<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>IMT Pulse sample review</title><style>
:root{{--bg:#f6f7f9;--card:#fff;--ink:#16181d;--mut:#5c6370;--acc:#0b5cad;--ok:#e3f4e8;--okb:#1f8a4c;--warn:#b3261e;--line:#e3e6ea}}
@media (prefers-color-scheme:dark){{:root{{--bg:#111316;--card:#1b1e23;--ink:#e8eaed;--mut:#9aa0a6;--acc:#7cb4ff;--ok:#16301f;--okb:#5fd08a;--warn:#ff8a80;--line:#2c3037}}}}
body{{margin:0;background:var(--bg);color:var(--ink);font:15px/1.5 -apple-system,system-ui,sans-serif}}
main{{max-width:820px;margin:0 auto;padding:16px}} h1{{font-size:22px}} h2{{margin-top:36px;border-bottom:2px solid var(--line);padding-bottom:6px}}
small{{color:var(--mut);font-weight:400;font-size:13px}} .card{{background:var(--card);border:1px solid var(--line);border-radius:12px;padding:14px 18px;margin:14px 0}}
.co{{border-left:4px solid var(--acc)}} .badge{{font-size:12px;background:#fff4d6;color:#7a5300;padding:2px 8px;border-radius:99px}}
@media (prefers-color-scheme:dark){{.badge{{background:#3d3210;color:#ffd77a}}}}
a{{color:var(--acc);text-decoration:none;font-weight:600}} .src{{color:var(--mut);font-size:12px}} .stories li{{margin-bottom:10px}} .stories p{{margin:2px 0}}
.why{{color:var(--mut);font-style:italic}} .q{{margin:10px 0}} .q ol{{margin:4px 0}} .q li.ok{{background:var(--ok);color:var(--okb);font-weight:600;border-radius:4px}}
.ex{{color:var(--mut);margin:2px 0 0}} .err{{color:var(--warn);font-weight:600}} summary{{cursor:pointer;font-weight:600;margin-top:8px}}
</style></head><body><main><h1>IMT Pulse: sample content for review</h1>
<p>Two sample editions generated by the real pipeline ({e(TITLE)}). Companies are placeholders. Links go to the original articles.</p>
{"".join(days)}</main></body></html>"""
open(f"{SRC}/review.html", "w").write(page)
print(f"wrote {SRC}/review.html")
